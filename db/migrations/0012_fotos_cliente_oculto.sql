-- =====================================================================
-- 0012_fotos_cliente_oculto.sql
-- Fotos de comprovação do Cliente Oculto (ex.: parede mofada, decorado mal
-- organizado, sujeira no PDV), ligadas a um pilar da avaliação.
-- A foto é reduzida no navegador (até 1600 px, JPEG) e guardada no próprio
-- banco, sem serviço de arquivos externo.
-- =====================================================================

create table if not exists co_fotos (
  id            integer generated by default as identity primary key,
  avaliacao_id  text not null references co_avaliacoes (id) on delete cascade,
  pilar_key     text,
  legenda       text,
  mime          text not null check (mime in ('image/jpeg', 'image/png', 'image/webp')),
  imagem        bytea not null,
  tamanho       integer not null,
  criado_em     timestamptz not null default now(),
  criado_por    uuid references usuarios (id_usuario)
);
create index if not exists idx_co_fotos_avaliacao on co_fotos (avaliacao_id);
